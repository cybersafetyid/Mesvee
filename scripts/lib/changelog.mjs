/**
 * Changelog helpers shared by the version bump and the release workflow.
 *
 * Entries are generated from git history using Conventional Commits
 * (`feat:`, `fix(scope):`, `feat!:` …). Commits that do not follow the
 * convention are kept under "Other changes" so nothing is silently dropped.
 */
import { execFileSync } from 'node:child_process';

/** Section order and headings. Types not listed here fall into "Other changes". */
const SECTIONS = [
  ['breaking', '⚠ Breaking changes'],
  ['feat', 'Features'],
  ['fix', 'Bug fixes'],
  ['perf', 'Performance'],
  ['refactor', 'Refactoring'],
  ['docs', 'Documentation'],
  ['test', 'Tests'],
  ['build', 'Build system'],
  ['ci', 'CI/CD'],
  ['style', 'Style'],
  ['other', 'Other changes'],
];

/** Commit subjects that are release bookkeeping, never user-facing. */
const IGNORED = [/^chore\(release\)/i, /^chore: release/i, /^merge /i];

/** Runs git and returns trimmed stdout, or null when git fails. */
export function git(cwd, ...args) {
  try {
    return execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return null;
  }
}

/** True when `cwd` is inside a git work tree. */
export function isGitRepo(cwd) {
  return git(cwd, 'rev-parse', '--is-inside-work-tree') === 'true';
}

/** The most recent `v*` tag reachable from HEAD, or null before the first release. */
export function lastTag(cwd) {
  return git(cwd, 'describe', '--tags', '--abbrev=0', '--match', 'v*');
}

/** `https://github.com/owner/repo` derived from the `origin` remote, or null. */
export function repoUrl(cwd) {
  const remote = git(cwd, 'remote', 'get-url', 'origin');
  const match = remote && remote.match(/github\.com[:/]([^/]+\/[^/]+?)(?:\.git)?$/);
  return match ? `https://github.com/${match[1]}` : null;
}

/** Commits since the last release tag (or the whole history) as `{hash, subject}`. */
export function commitsSince(cwd, tag) {
  const range = tag ? [`${tag}..HEAD`] : [];
  const out = git(cwd, 'log', ...range, '--no-merges', '--pretty=format:%h%x1f%s');
  if (!out) return [];
  return out
    .split('\n')
    .map((line) => {
      const [hash, subject] = line.split('\x1f');
      return { hash, subject };
    })
    .filter((c) => c.subject && !IGNORED.some((re) => re.test(c.subject)));
}

/** Parses `type(scope)!: description`; non-conventional subjects become `other`. */
export function parseCommit({ hash, subject }) {
  const m = subject.match(/^(\w+)(?:\(([^)]+)\))?(!)?:\s+(.+)$/);
  if (!m) return { hash, type: 'other', scope: null, breaking: false, text: subject };
  const [, type, scope, bang, text] = m;
  const known = SECTIONS.some(([key]) => key === type.toLowerCase());
  return {
    hash,
    type: known ? type.toLowerCase() : 'other',
    scope: scope ?? null,
    breaking: Boolean(bang),
    text,
  };
}

/** Renders one release entry (heading + grouped bullet lists) as markdown. */
export function renderEntry({ version, date, commits, repo, previousTag }) {
  const groups = new Map(SECTIONS.map(([key]) => [key, []]));
  for (const commit of commits.map(parseCommit)) {
    groups.get(commit.breaking ? 'breaking' : commit.type).push(commit);
  }

  const compare = repo && previousTag ? `${repo}/compare/${previousTag}...v${version}` : null;
  const lines = [`## ${compare ? `[${version}](${compare})` : version} - ${date}`, ''];

  let any = false;
  for (const [key, title] of SECTIONS) {
    const items = groups.get(key);
    if (!items.length) continue;
    any = true;
    lines.push(`### ${title}`, '');
    for (const c of items) {
      const scope = c.scope ? `**${c.scope}:** ` : '';
      const ref = repo ? ` ([${c.hash}](${repo}/commit/${c.hash}))` : ` (${c.hash})`;
      lines.push(`- ${scope}${c.text}${ref}`);
    }
    lines.push('');
  }
  if (!any) lines.push('- Maintenance release.', '');
  return lines.join('\n');
}

const HEADER = `# Changelog

All notable changes to Mesvee are documented here. This file is generated by
\`pnpm run bump:*\` from Conventional Commit messages — do not edit released
sections by hand.

`;

/** Inserts `entry` directly below the file header, keeping older releases intact. */
export function prependEntry(existing, entry) {
  if (!existing) return `${HEADER}${entry}\n`;
  const first = existing.search(/^## /m);
  if (first === -1) return `${existing.trimEnd()}\n\n${entry}\n`;
  return `${existing.slice(0, first)}${entry}\n${existing.slice(first)}`;
}

/** Extracts the body of one version's section (used for GitHub release notes). */
export function extractSection(changelog, version) {
  const escaped = version.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const start = changelog.search(new RegExp(`^## \\[?${escaped}\\]?(\\(|\\s|$)`, 'm'));
  if (start === -1) return null;
  const rest = changelog.slice(start);
  const next = rest.slice(3).search(/^## /m);
  const section = next === -1 ? rest : rest.slice(0, next + 3);
  return section.split('\n').slice(1).join('\n').trim();
}
