import { chromium } from '@playwright/test';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, locale: 'id-ID' });
await page.goto('http://127.0.0.1:1420/?fresh=1', { waitUntil: 'networkidle' });
await page.waitForTimeout(500);
await page.locator('button[aria-label*="WhatsApp"]').first().click();
await page.waitForTimeout(500);
await page.getByRole('button', { name: 'Aksi lainnya' }).click();
await page.waitForTimeout(400);
const trayVisible = await page.getByRole('toolbar', { name: 'Aksi lainnya' }).isVisible();
const surface = await page.locator('.service-surface').boundingBox();
const tray = await page.getByRole('toolbar', { name: 'Aksi lainnya' }).boundingBox();
await page.screenshot({ path: 'screenshots/14-service-tray.png' });
await page.getByRole('button', { name: 'Ukuran tampilan' }).click();
await page.waitForTimeout(400);
const zoomTray = await page.getByRole('toolbar', { name: 'Ukuran tampilan' }).isVisible();
await page.screenshot({ path: 'screenshots/15-service-zoom-tray.png' });
console.log(JSON.stringify({ trayVisible, zoomTray, surface, tray }, null, 2));
await browser.close();
